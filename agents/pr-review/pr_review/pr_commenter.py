"""PR commenter for PR review agent - posts review to GitHub."""

from pr_review.reviewer import Review, InlineComment
from pr_review.github_client import GitHubClient


SEVERITY_PREFIX = {
    "error": "🔴 **Error:**",
    "warning": "🟡 **Warning:**",
    "suggestion": "🔵 **Suggestion:**",
}

VERDICT_EMOJI = {
    "approved": "✅",
    "changes_requested": "❌",
    "comment": "💬",
}


def format_summary_comment(review: Review) -> str:
    """Format the summary comment for GitHub PR."""
    verdict_emoji = VERDICT_EMOJI.get(review.verdict, "💬")

    comment = f"""## 🤖 AI Code Review

{review.summary}

---
**Verdict:** {review.verdict} {verdict_emoji}

<sub>Generated by pr-review using Claude Code with full repository context.</sub>
"""
    return comment


def format_inline_comments(
    review: Review,
    commit_sha: str,
    changed_files: list[dict],
) -> list[dict]:
    """Format inline comments for GitHub PR review API.

    Args:
        review: The Review object with inline comments
        commit_sha: The commit SHA to comment on
        changed_files: List of changed files from GitHub API (to get positions)

    Returns:
        List of comment dicts for the GitHub API
    """
    # Build a map of filename -> diff content for position calculation
    # Note: GitHub requires the position in the diff, not the line number in the file
    # For simplicity, we'll use the line number and let GitHub figure it out
    # In production, you'd need to parse the diff to get the correct position

    comments = []
    for comment in review.inline_comments:
        # Map severity to prefix
        prefix = SEVERITY_PREFIX.get(comment.severity, "🔵 **Suggestion:**")

        comment_body = f"{prefix} {comment.comment}"

        # Build the comment dict
        # Note: GitHub review comments need either:
        # - path + position (position in the diff)
        # - path + line + side (line in the new file)
        # We'll use path + line + side for simplicity
        comment_dict = {
            "path": comment.file,
            "line": comment.line,
            "side": "RIGHT",  # Comment on the new version of the file
            "body": comment_body,
        }
        comments.append(comment_dict)

    return comments


def post_review(
    github: GitHubClient,
    owner: str,
    repo: str,
    pr_number: int,
    pr: dict,
    review: Review,
    dry_run: bool = False,
) -> None:
    """Post the review to GitHub PR.

    Args:
        github: GitHubClient instance
        owner: Repo owner
        repo: Repo name
        pr_number: PR number
        pr: PR metadata dict (for commit SHA)
        review: Review object to post
        dry_run: If True, print instead of posting
    """
    commit_sha = pr.get("head", {}).get("sha", "")

    # Format comments
    summary = format_summary_comment(review)

    if dry_run:
        print("=" * 60, file=None)
        print("DRY RUN - Would post the following review:", file=None)
        print("=" * 60, file=None)
        print(summary, file=None)
        print(file=None)
        if review.inline_comments:
            print(f"Would post {len(review.inline_comments)} inline comments:", file=None)
            for comment in review.inline_comments:
                prefix = SEVERITY_PREFIX.get(comment.severity, "🔵 **Suggestion:**")
                print(f"  [{comment.file}:{comment.line}] {prefix} {comment.comment[:100]}", file=None)
        print("=" * 60, file=None)
        return

    # Get changed files for position mapping
    changed_files = github.get_pr_files(owner, repo, pr_number)

    # Format inline comments
    inline_comments = format_inline_comments(review, commit_sha, changed_files)

    # Post the review
    github.create_pr_review(
        owner=owner,
        repo=repo,
        pr_number=pr_number,
        commit_sha=commit_sha,
        body=summary,
        comments=inline_comments,
    )
